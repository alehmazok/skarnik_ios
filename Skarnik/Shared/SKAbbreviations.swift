import Foundation

/// An abbreviation found in a text: its range there (UTF-16), the abbreviation as written and its expansion.
struct SKAbbreviationMatch: Equatable {
    let range: NSRange
    let abbreviation: String
    let expansion: String
}

/// Labels such as «разг.» or «в разн. знач.» with their full text in Russian (list from Aleh, 2026-11-15,
/// plus the forms Бел-Рус actually uses: «жен.», «муж.», «совер.», «несовер.»). In the data only Бел-Рус
/// abbreviates them, inside its green label spans; Рус-Бел spells them out.
///
/// A space after a dot is optional when matching («и т.п.» = «и т. п.»), and an abbreviation never starts
/// or ends inside a word («ж.» is not found in «муж.»). Longer abbreviations win («в знач. прил.» over «прил.»).
enum SKAbbreviations {

    static func expansion(of abbreviation: String) -> String? {
        byKey[normalize(abbreviation)]
    }

    static func matches(in text: String) -> [SKAbbreviationMatch] {
        guard let pattern else { return [] }
        let string = text as NSString
        return pattern.matches(in: text, range: NSRange(location: 0, length: string.length)).compactMap { match in
            let value = string.substring(with: match.range)
            guard let expansion = byKey[normalize(value)] else { return nil }
            return SKAbbreviationMatch(range: match.range, abbreviation: value, expansion: expansion)
        }
    }

    private static let byKey: [String: String] = {
        var map: [String: String] = [:]
        for line in list.split(separator: "\n") {
            let parts = line.trimmingCharacters(in: .whitespaces).components(separatedBy: " | ")
            guard parts.count == 2 else { continue }
            for key in parts[0].components(separatedBy: ", ") {
                map[normalize(key)] = parts[1].trimmingCharacters(in: .whitespaces)
            }
        }
        return map
    }()

    private static let pattern: NSRegularExpression? = {
        let alternatives = byKey.keys
            .sorted { $0.count != $1.count ? $0.count > $1.count : $0 < $1 }
            .map(pattern(of:))
        return try? NSRegularExpression(pattern: alternatives.joined(separator: "|"))
    }()

    private static let space = "[ \\u00a0]"

    private static func pattern(of key: String) -> String {
        var result = "(?:"
        if key.first?.isLetter == true { result += "(?<![\\p{L}-])" }
        let chars = Array(key)
        for (index, char) in chars.enumerated() {
            switch char {
            case " ": result += space + "+"
            case ".":
                result += "\\."
                if index < chars.count - 1 { result += space + "*" }
            case "-": result += "\\-"
            default: result.append(char)
            }
        }
        return result + "(?!\\p{L}))"
    }

    /// No space after a dot, other spaces (also `&nbsp;`) as one space.
    private static func normalize(_ text: String) -> String {
        text.trimmingCharacters(in: .whitespaces)
            .replacingOccurrences(of: "\\.[ \\u00a0]+", with: ".", options: .regularExpression)
            .replacingOccurrences(of: "[ \\u00a0]+", with: " ", options: .regularExpression)
    }

